package dsaa;

public class StackDemo<T> {

    private static class Node<T> {
        T data;
        Node<T> next;
        Node(T data) { this.data = data; }
    }

    private Node<T> top;

    public void push(T item) {
        Node<T> node = new Node<>(item);
        node.next = top;
        top = node;
    }

    public T pop() {
        if (top == null) return null;
        T data = top.data;
        top = top.next;
        return data;
    }

    public T peek() {
        return (top == null) ? null : top.data;
    }

    public boolean isEmpty() {
        return top == null;
    }
}
